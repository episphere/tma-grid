    def test_removing_a_local_image_clears_the_active_source(self):
        with sync_playwright() as p:
            browser = p.chromium.launch(channel=os.getenv("TMA_BROWSER_CHANNEL", "msedge"), headless=True)
            page = browser.new_page(viewport={"width": 1440, "height": 1000})
            try:
                page.goto(os.getenv("TMA_BASE_URL", "http://localhost:8000"), wait_until="networkidle", timeout=90000)
                image_path = next(Path(__file__).resolve().parents[1].glob("*.png"))
                expect(page.locator("#fileInput")).to_be_enabled(timeout=30000)
                page.locator("#fileInput").set_input_files(str(image_path))
                page.wait_for_function("Boolean(window.loadedImg)", timeout=90000)
                expect(page.locator("#upload .btn-proceed")).to_be_enabled()
                page.get_by_role("tab", name="Image URL", exact=True).click()
                page.locator("#imageUrlInput").fill("not an image url")
                page.locator("#loadImageUrlBtn").click()
                expect(page.locator("#imageUrlInput")).to_have_attribute("aria-invalid", "true")
                expect(page.locator("#imageLoadStatus")).to_contain_text("complete http:// or https://")
                self.assertTrue(page.evaluate("Boolean(window.loadedImg)"), "An invalid URL must not erase the working image")
                page.get_by_role("tab", name="Local file", exact=True).click()
                page.locator("#remove-file").click()
                page.wait_for_function("!window.loadedImg")
                expect(page.locator("#upload .btn-proceed")).to_be_disabled()
                expect(page.locator("#uploadSummaryName")).to_have_text("None selected")
                expect(page.locator("#upload .stage-file-context")).to_have_text("No image selected")
            finally:
                browser.close()


